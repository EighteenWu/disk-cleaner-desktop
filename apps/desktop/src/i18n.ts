export function readStoredLanguage(): LanguageCode {
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (isLanguageCode(stored)) {
    return stored;
  }

  const browserLanguage = window.navigator.language.toLowerCase();
  if (browserLanguage.startsWith("ja")) return "ja-JP";
  if (browserLanguage.startsWith("fr")) return "fr-FR";
  if (browserLanguage.startsWith("de")) return "de-DE";
  if (browserLanguage.startsWith("en")) return "en-US";
  return "zh-CN";
}

export function storeLanguage(language: LanguageCode) {
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function isLanguageCode(value: unknown): value is LanguageCode {
  return value === "zh-CN" || value === "en-US" || value === "ja-JP" || value === "fr-FR" || value === "de-DE";
}

export function createTranslator(language: LanguageCode) {
  return (key: string, values: Record<string, string | number> = {}) => translate(language, key, values);
}

export function translate(
  language: LanguageCode,
  key: string,
  values: Record<string, string | number> = {}
): string {
  const template = dictionaries[language][key] ?? dictionaries["en-US"][key] ?? dictionaries["zh-CN"][key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

