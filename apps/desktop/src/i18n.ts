export function localizedCleanupStatusLabel(language: LanguageCode, candidate: CleanupCandidate): string {
  if (candidate.category === "大文件") {
    return translate(language, "cleanup.analysisOnly");
  }

  if (candidate.reason.includes("暂不支持")) {
    return translate(language, "cleanup.unsupported");
  }

  if (candidate.riskLevel === "blocked" || candidate.deleteStrategy === "skip") {
    return translate(language, "cleanup.blocked");
  }

  if (candidate.selected && candidate.defaultSelected) {
    return translate(language, "cleanup.default");
  }

  if (candidate.riskLevel === "safeRecommended") {
    return translate(language, "cleanup.ready");
  }

  if (candidate.riskLevel === "cautiousRecommended") {
    return translate(language, "cleanup.confirmAfterReview");
  }

  return localizedRiskLabel(language, candidate.riskLevel);
}

